interface IconProps {
  name: string;
  size?: number;
  className?: string;
}

/** Keys already reported, so an unknown icon warns once instead of on every render. */
const warnedKeys = new Set<string>();

export function Icon({ name, size = 18, className = "" }: IconProps) {
  // Legacy CDN class support: "ti ti-clipboard-list" -> "clipboard-list"
  const iconKey = name
    .replace(/^ti ti-/i, "")
    .replace(/^ti-/i, "")
    .replace(/\s+/g, "")
    .toLowerCase();

  const IconComp = iconMap[iconKey] ?? iconMap[iconKey.replace(/_/g, "-")];

  if (!IconComp) {
    if (!warnedKeys.has(iconKey)) {
      warnedKeys.add(iconKey);
      console.warn(`[Icon] Unknown icon: "${name}" (resolved: "${iconKey}")`);
    }
    return (
      <span
        className={`inline-flex items-center justify-center ${className}`}
        style={{ width: size, height: size }}
      >
        ?
      </span>
    );
  }

  return <IconComp width={size} height={size} className={className} />;
}
